/** Renders the icon for a nav href, or nothing if that route has no glyph
 * registered -- an unknown href must never crash the sidebar, it just
 * renders the label without an icon (and the flex layout still aligns,
 * since the label is what carries the row height). */
export function NavIcon({ href, className }: { href: string; className?: string }) {
  const paths = PATHS[href];
  if (!paths) return null;
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width="18"
      height="18"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden
    >
      {paths}
    </svg>
  );
}
